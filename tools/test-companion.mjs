import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const code = await readFile(new URL('../companion.js', import.meta.url), 'utf8');
const { Companion, renderLine, localDay, timePeriod } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
let date = new Date(2026, 8, 6, 23, 59);
let saved = 0;
const settings = {};
const ctx = { characters: [{avatar:'a.png', name:'甲'}, {avatar:'b.png', name:'乙'}], characterId:0, chatId:'one', chat:[{mes:'old'}] };
const make = () => new Companion(settings, () => ctx, () => saved++, () => date);
let cat = make();
const append = (extra = {}) => {ctx.chat.push({mes:'new reply', send_date:`stamp-${saved}`, ...extra}); return ctx.chat.length - 1;};
assert.equal(cat.values().今日层数, 0);
assert.equal(cat.receive(0), false, 'history is never counted');
cat.start('normal');
let id = append({is_user:true});
assert.equal(cat.receive(id), false);
id = append();
assert.equal(cat.receive(id), true);
assert.equal(cat.receive(id), false, 'duplicate event');
assert.equal(cat.values().今日层数, 1);
assert.equal(cat.values().今日卡数, 1);
for (const type of ['regenerate','swipe','continue','quiet','impersonate']) {
    cat.start(type);
    assert.equal(cat.receive(append(), type), false, type);
}
cat = make();
assert.equal(cat.values().今日层数, 1, 'refresh persists totals');
assert.equal(cat.receive(0), false);
cat.start('normal', true);
assert.equal(cat.receive(append()), false, 'dry run');
cat.start('normal');
assert.equal(cat.receive(append({is_system:true})), false);
assert.equal(cat.receive(append({mes:''})), false);
assert.equal(cat.receive(append({swipe_id:1})), false);
assert.equal(cat.receive(append()), true);
assert.equal(cat.values().今日层数, 2);
cat.start('normal');
ctx.chatId = 'other'; ctx.chat = [];
assert.equal(cat.receive(append()), false, 'late reply after switching');
cat.baseline();
cat.start('normal');
assert.equal(cat.receive(append()), true);
assert.equal(cat.values().今日卡数, 1, 'same card, different chats');
ctx.characterId = 1; ctx.chatId = 'b'; ctx.chat = [];
cat.baseline(); cat.start('normal'); cat.receive(append());
assert.equal(cat.values().今日卡数, 2);
ctx.groupId = 'g'; ctx.characterId = undefined; ctx.chatId='group'; ctx.chat=[];
cat.baseline(); cat.start('normal'); cat.receive(append({original_avatar:'a.png',name:'甲'}));
cat.start('normal'); cat.receive(append({original_avatar:'c.png',name:'丙'}));
assert.equal(cat.values().今日卡数, 3, 'group avatars deduplicate across solo chats');
cat.start('normal'); date = new Date(2026,8,7,0,1); cat.receive(append({original_avatar:'c.png'}));
assert.equal(cat.values().今日层数, 1, 'reply belongs to arrival day');
assert.equal(cat.values().今日卡数, 1);
assert.equal(settings.companionDay.date, '2026-09-07');
assert.equal(localDay(date), '2026-09-07');
assert.equal(timePeriod(new Date(2026,8,7,9)), '上午');
assert.equal(renderLine({report:'现在{时间}，{今日层数}层'}, 'report', cat.values()), '现在00:01，1层');
assert.equal(renderLine({petting:'一\n二'}, 'petting', {}, () => .99), '二');
assert.equal(renderLine({petting:'  \n'}, 'petting', {}), '呼噜呼噜～');
assert.equal(renderLine({petting:'<img src=x> {未知}'}, 'petting', {}), '<img src=x> {未知}');
// A brand-new chat may gain its ID between generation start and first reply.
ctx.groupId = null; ctx.characterId = 0; ctx.chatId=null; ctx.chat=[];
cat.baseline(); cat.start('normal'); ctx.chatId='new';
assert.equal(cat.receive(append()), true);
console.log('PASS: new replies, deduplication, refresh, history, excluded generation types, chat switches, groups, midnight, templates.');
